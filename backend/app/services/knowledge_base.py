    """按类别统计chunk数量"""
    cats = {"brand": 0, "product": 0, "shipping": 0, "return": 0, "promo": 0, "faq": 0}
    for c in CHUNKS:
        cid = c[0]
        if cid.startswith("brand_"): cats["brand"] += 1
        elif cid.startswith("prod_"): cats["product"] += 1
        elif cid.startswith("ship_"): cats["shipping"] += 1
        elif cid.startswith("return_"): cats["return"] += 1
        elif cid.startswith("promo_"): cats["promo"] += 1
        elif cid.startswith("faq_"): cats["faq"] += 1
    return cats