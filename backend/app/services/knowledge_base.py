# ========== RAG 检索 ==========

def _tokenize(text: str) -> List[str]:
    """中文分词（字符级+词级混合分词）"""
    text_lower = text.lower()
    tokens = []

    # 1. 提取英文词、数字
    for m in re.finditer(r'[a-zA-Z]+|\d+', text_lower):
        tokens.append(m.group())

    # 2. 提取中文连续片段，按字符拆分+bigram
    for m in re.finditer(r'[\u4e00-\u9fff]+', text_lower):
        chinese = m.group()
        # 单字
        for ch in chinese:
            tokens.append(ch)
        # 二字bigram
        for i in range(len(chinese) - 1):
            tokens.append(chinese[i:i + 2])
        # 三字trigram
        for i in range(len(chinese) - 2):
            tokens.append(chinese[i:i + 3])
        # 整词
        tokens.append(chinese)

    return list(set(tokens))


def _relevance_score(query: str, chunk_keywords: str, chunk_content: str) -> float:
    """
    计算查询与知识块的相关性分数
    综合考虑：关键词匹配 + 内容语义重叠 + IDF权重
    """
    query_tokens = set(_tokenize(query))
    kw_tokens = set(_tokenize(chunk_keywords))
    content_tokens = set(_tokenize(chunk_content))

    # 关键词匹配得分（权重0.5）
    if query_tokens and kw_tokens:
        kw_overlap = len(query_tokens & kw_tokens) / len(query_tokens)
    else:
        kw_overlap = 0

    # 内容匹配得分（权重0.3）
    if query_tokens and content_tokens:
        content_overlap = len(query_tokens & content_tokens) / len(query_tokens)
    else:
        content_overlap = 0

    # 标题命中加分（权重0.2）
    # 检查标题关键词是否直接命中查询词
    title_bonus = 0
    for qt in query_tokens:
        if qt in chunk_keywords:
            title_bonus += 0.1
    title_bonus = min(title_bonus, 0.3)  # 最多加0.3

    return kw_overlap * 0.5 + content_overlap * 0.3 + title_bonus


def search_knowledge(query: str, top_k: int = 5) -> str:
    """
    RAG检索：从知识库中检索与查询最相关的Top-K个chunk
    返回拼接后的知识文本
    """
    scored = []
    for chunk_id, title, keywords, content in CHUNKS:
        score = _relevance_score(query, keywords, content)
        if score > 0:
            scored.append((score, title, content))

    # 按得分降序排列
    scored.sort(key=lambda x: x[0], reverse=True)

    if not scored:
        # 无匹配时返回品牌信息+发货+退换政策+FAQ
        fallback_ids = ["brand_01", "brand_02", "ship_01", "return_01", "return_02", "faq_15", "faq_34"]
        fallback = [c for c in CHUNKS if c[0] in fallback_ids]
        return "\n\n".join(f"[{t}] {c}" for _, t, _, c in fallback)

    # 取top_k个结果
    top_chunks = scored[:top_k]
    return "\n\n".join(f"[{title}] {content}" for _, title, content in top_chunks)


def search_knowledge_structured(query: str, top_k: int = 5) -> List[dict]:
    """
    RAG检索：返回结构化结果（包含标题、内容、得分），供前端展示
    """
    scored = []
    for chunk_id, title, keywords, content in CHUNKS:
        score = _relevance_score(query, keywords, content)
        if score > 0:
            scored.append({"title": title, "content": content, "score": round(score, 3)})

    scored.sort(key=lambda x: x["score"], reverse=True)

    if not scored:
        fallback_ids = ["brand_01", "brand_02", "ship_01", "return_01", "return_02"]
        fallback = [c for c in CHUNKS if c[0] in fallback_ids]
        return [{"title": t, "content": c, "score": 0.1} for _, t, _, c in fallback]

    return scored[:top_k]


