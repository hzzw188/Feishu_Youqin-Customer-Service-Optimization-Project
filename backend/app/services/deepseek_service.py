def analyze_and_reply(customer_message: str, session_context: str = "") -> dict:
    """
    RAG + DeepSeek：检索知识库 → 拼接提示词 → 调用DeepSeek分析
    session_context: 对话历史（最近几条消息），用于理解上下文和情绪演变
    """
    # ====== Step 1: RAG 检索 ======
    kb_context = search_knowledge(customer_message, top_k=5)

    # ====== Step 2: 构建提示词 ======
    if session_context:
        context_section = f"""## 对话历史（按时间正序，最后一行是当前客户消息）
请结合对话历史理解客户的真实诉求和情绪演变趋势。如果客户情绪从平稳变愤怒，或从愤怒被安抚到平稳，请在 emotion 字段反映最新状态。

{session_context}"""
    else:
        context_section = "## 对话历史\n新会话（首次互动）"

    user_prompt = f"""## 知识库检索结果（RAG Top-5）
以下是从知识库中检索到的与客户消息最相关的信息，请基于这些信息回答问题：

{kb_context}

{context_section}

## 当前需要分析的客户消息
{customer_message}

请根据以上知识库内容和对话历史，完成以下分析并给出回复：
1. 结合对话历史识别客户真实意图（表面问题背后的需求）
2. 基于对话趋势判断客户最新情绪状态（情绪可能升级或缓和）
3. 评估风险等级（情绪激动或多次催促应升级风险）
4. 判断是否可自动回答（已问过的问题不要重复回答）
5. 生成最合适的回复（延续对话，不要重复已说过的内容）

严格按JSON格式输出，不要包含markdown代码块标记。"""

    # ====== Step 3: 调用 DeepSeek ======
    try:
        response = client.chat.completions.create(
            model="deepseek-chat",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.6,
            max_tokens=1200,
            extra_body={"response_format": {"type": "json_object"}},
        )

        content = response.choices[0].message.content.strip()
        # 清理可能的 markdown 残留
        if content.startswith("```"):
            lines = content.split("\n")
            content = "\n".join(lines[1:-1])
        if "```json" in content:
            content = content.replace("```json", "").replace("```", "")
        result = json.loads(content)
        return result

    except Exception as e:
        print(f"DeepSeek API error: {e}")
        return _fallback_analyze(customer_message)


